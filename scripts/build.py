"""Write every reader-facing file from the data under data/.

    python scripts/build.py           write the files
    python scripts/build.py --check   exit 1 if any generated file differs from what the data would produce

Generated: LINKS.md, bookmarks.html, bookmarks-full.html, INDEX.md, domains/README.md, one page per
populated domain, .lycheeignore, and the blocks between markers in README.md. All files are UTF-8 with LF line endings.

--check also compares the SHA-256 of LINKS.md and bookmarks.html with data/compact.lock. Another
TeamStarWolf system reads LINKS.md, so a change to either file has to be made on purpose: update the
lock in the same change.
"""
from __future__ import annotations

import hashlib
import html
import re
import sys
from pathlib import Path

import catalog
from catalog import ROOT

GENERATED_NOTE = "<!-- Generated by scripts/build.py from data/. Do not edit this file; change the data and rebuild. -->"
LIBRARY = "https://github.com/TeamStarWolf/TeamStarWolf/blob/main/hubs/"


def md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def plural(n: int, one: str, many: str | None = None) -> str:
    return f"{n} {one if n == 1 else (many or one + 's')}"


class Catalog:
    def __init__(self, data: Path = catalog.DATA):
        self.tax = catalog.load_taxonomy(data)
        self.records = catalog.load_resources(data)
        self.compact = catalog.load_compact(data)
        self.ignore = catalog.read_yaml(data / "link-check-ignore.yaml") or []
        self.by_id = {r["id"]: r for r in self.records}
        self.kinds = {k["id"]: k for k in self.tax["kinds"]}
        self.costs = {c["id"]: c for c in self.tax["costs"]}
        self.domains = {d["id"]: d for d in self.tax["domains"]}
        self.active = [r for r in self.records if catalog.is_active(r)]

    # ---- lookups
    def primary(self, domain: str, section: str) -> list[dict]:
        return [r for r in self.active if r["domain"] == domain and r["section"] == section]

    def cross(self, domain: str, section: str) -> list[dict]:
        ref = f"{domain}/{section}"
        return [r for r in self.active if ref in (r.get("also_in") or [])]

    def domain_count(self, domain: str) -> int:
        return sum(1 for r in self.active if r["domain"] == domain)

    def populated(self) -> list[dict]:
        return [d for d in self.tax["domains"] if self.domain_count(d["id"])]

    def section_title(self, domain: str, section: str) -> str:
        return next(s["title"] for s in self.domains[domain]["sections"] if s["id"] == section)

    # ---- the compact set
    def links_md(self) -> str:
        c = self.compact
        lines = [f"# {c['title']}", "", c["intro"], "", ""]
        for folder in c["folders"]:
            lines += [f"## {folder['title']}", ""]
            if folder.get("links"):
                lines += [self._md_link(link) for link in folder["links"]] + [""]
            for sub in folder.get("sections") or []:
                lines += ["", f"### {sub['title']}", ""] + [self._md_link(link) for link in sub["links"]]
            if folder.get("sections"):
                lines.append("")
        return "\n".join(lines)

    def _md_link(self, link: dict) -> str:
        return f"- [{link['label']}]({catalog.compact_address(link, self.by_id)})"

    def bookmarks_html(self) -> str:
        out = self._netscape_head()
        out.append(f"    <DT><H3>{html.escape(self.compact['title'], quote=False)}</H3>")
        out.append("    <DL><p>")
        for folder in self.compact["folders"]:
            out.append(f"        <DT><H3>{html.escape(folder['title'], quote=False)}</H3>")
            out.append("        <DL><p>")
            for link in folder.get("links") or []:
                out.append(" " * 12 + self._html_link(link["label"], catalog.compact_address(link, self.by_id)))
            for sub in folder.get("sections") or []:
                out.append(f"            <DT><H3>{html.escape(sub['title'], quote=False)}</H3>")
                out.append("            <DL><p>")
                for link in sub["links"]:
                    out.append(" " * 16 + self._html_link(link["label"], catalog.compact_address(link, self.by_id)))
                out.append("            </DL><p>")
            out.append("        </DL><p>")
        out += ["    </DL><p>", "</DL><p>", ""]
        return "\n".join(out)

    @staticmethod
    def _netscape_head() -> list[str]:
        return [
            "<!DOCTYPE NETSCAPE-Bookmark-file-1>",
            '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
            "<TITLE>Bookmarks</TITLE>",
            "<H1>Bookmarks</H1>",
            "<DL><p>",
        ]

    @staticmethod
    def _html_link(label: str, url: str) -> str:
        return f'<DT><A HREF="{html.escape(url, quote=True)}">{html.escape(label, quote=False)}</A>'

    # ---- the full catalog as an import file
    def bookmarks_full_html(self) -> str:
        out = self._netscape_head()
        out.append("    <DT><H3>Cybersecurity and IT Resources (full catalog)</H3>")
        out.append("    <DL><p>")
        for dom in self.populated():
            out.append(f"        <DT><H3>{html.escape(dom['title'], quote=False)}</H3>")
            out.append("        <DL><p>")
            for sec in dom["sections"]:
                recs = self.primary(dom["id"], sec["id"])
                if not recs:
                    continue
                out.append(f"            <DT><H3>{html.escape(sec['title'], quote=False)}</H3>")
                out.append("            <DL><p>")
                for r in recs:
                    out.append(" " * 16 + self._html_link(r["name"], r["url"]))
                out.append("            </DL><p>")
            out.append("        </DL><p>")
        out += ["    </DL><p>", "</DL><p>", ""]
        return "\n".join(out)

    # ---- domain pages
    def checked_sentence(self, recs: list[dict]) -> str:
        dates = sorted({r["checked"]["date"] for r in recs})
        if not dates:
            return ""
        if dates[0] == dates[-1]:
            return f"Every address on this page was opened and read on {dates[0]}."
        return f"Every address on this page was opened and read between {dates[0]} and {dates[-1]}."

    def row(self, r: dict) -> str:
        name = f"[{md_cell(r['name'])}]({r['url']})"
        if r.get("formerly"):
            name += f" (formerly {md_cell(r['formerly'])})"
        return "| " + " | ".join([
            name,
            md_cell(r["publisher"]),
            md_cell(r["description"]),
            self.kinds[r["kind"]]["label"],
            self.costs[r["cost"]]["label"],
        ]) + " |"

    def domain_page(self, dom: dict) -> str:
        did = dom["id"]
        sections = [s for s in dom["sections"] if self.primary(did, s["id"]) or self.cross(did, s["id"])]
        own = [r for r in self.active if r["domain"] == did]
        shown = list(own)
        for s in sections:
            shown += self.cross(did, s["id"])
        lines = [GENERATED_NOTE, "", f"# {dom['title']}", "", f"> {dom['covers']}", ""]
        intro = f"Part of the [domain list](README.md). {plural(len(own), 'resource')} in {plural(len(sections), 'section')}. {dom['boundary']}"
        lines += [intro, ""]
        if dom.get("library_hub"):
            hub = dom["library_hub"]
            lines += [f"For references, how-to guides, and learning paths on this subject, see the TeamStarWolf library's [matching domain page]({LIBRARY}{hub}.md).", ""]
        lines += ["| Section | The question it answers | Resources |", "|---|---|---|"]
        for s in sections:
            n = len(self.primary(did, s["id"]))
            lines.append(f"| [{s['title']}](#{catalog.slug(s['title'])}) | {md_cell(s['question'])} | {n} |")
        lines.append("")
        for s in sections:
            lines += [f"## {s['title']}", "", s["question"], ""]
            lines += ["| Resource | Run by | What it is and when to use it | Kind | Cost |", "|---|---|---|---|---|"]
            for r in self.primary(did, s["id"]):
                lines.append(self.row(r))
            cross = self.cross(did, s["id"])
            for r in cross:
                lines.append(self.row(r))
            lines.append("")
            if cross:
                homes = ", ".join(
                    f"{r['name']} ([{self.domains[r['domain']]['title']}]({r['domain']}.md#{catalog.slug(self.section_title(r['domain'], r['section']))}))"
                    for r in cross
                )
                lines += [f"Listed here from another domain: {homes}.", ""]
        lines += [self.checked_sentence(shown) + " Kind and Cost are defined in the [README](../README.md#how-to-read-an-entry).", ""]
        return "\n".join(lines)

    def domains_readme(self) -> str:
        lines = [GENERATED_NOTE, "", "# Domains", "",
                 "> The catalog, grouped by domain. Each domain page lists its resources by the question a practitioner asks, with one sentence on what each resource is, who runs it, what kind of thing it is, and what it costs.", ""]
        total = len(self.active)
        lines += [f"{plural(total, 'resource')} in {plural(len(self.populated()), 'domain')}. A domain is listed without a link until it holds its first resource.", ""]
        for group in self.tax["groups"]:
            lines += [f"## {group['title']}", "", group["note"], "",
                      "| Domain | What it covers | Where its boundary is | Resources |", "|---|---|---|---|"]
            for dom in self.tax["domains"]:
                if dom["group"] != group["id"]:
                    continue
                n = self.domain_count(dom["id"])
                title = f"[{dom['title']}]({dom['id']}.md)" if n else dom["title"]
                lines.append(f"| {title} | {md_cell(dom['covers'])} | {md_cell(dom['boundary'])} | {n} |")
            lines.append("")
        lines += ["Every resource A to Z: the [index](../INDEX.md).", ""]
        return "\n".join(lines)

    # ---- A to Z
    @staticmethod
    def sort_key(r: dict) -> str:
        return re.sub(r"^(the|a|an)\s+", "", r["name"].casefold())

    def index_md(self) -> str:
        recs = sorted(self.active, key=self.sort_key)
        lines = [GENERATED_NOTE, "", "# Index, A to Z", "",
                 f"> Every resource in the catalog by name: {len(recs)} entries. Each name links to the resource; the domain links to its place in the catalog.", ""]
        letters: dict[str, list[dict]] = {}
        for r in recs:
            first = self.sort_key(r)[0].upper()
            letters.setdefault(first if first.isalpha() else "0-9", []).append(r)
        lines += [" · ".join(f"[{k}](#{k.lower()})" for k in letters), ""]
        for letter, rs in letters.items():
            lines += [f"## {letter}", "", "| Resource | Run by | Domain | Kind | Cost |", "|---|---|---|---|---|"]
            for r in rs:
                dom = self.domains[r["domain"]]
                where = f"[{dom['title']}](domains/{r['domain']}.md#{catalog.slug(self.section_title(r['domain'], r['section']))})"
                lines.append(f"| [{md_cell(r['name'])}]({r['url']}) | {md_cell(r['publisher'])} | {where} | {self.kinds[r['kind']]['label']} | {self.costs[r['cost']]['label']} |")
            lines.append("")
        return "\n".join(lines)

    # ---- README blocks
    def block_counts(self) -> str:
        compact_links = sum(len(links) for _, _, links in catalog.compact_lists(self.compact))
        held = len(self.records) - len(self.active)
        text = (f"The catalog holds {plural(len(self.active), 'resource')} in {plural(len(self.populated()), 'domain')}, "
                f"each opened and read before it was described. The compact bookmark set holds {compact_links} bookmarks "
                f"in {plural(len(self.compact['folders']), 'folder')}.")
        if held:
            text += (f" The data also keeps {plural(held, 'record')} that {'is' if held == 1 else 'are'} not shown, "
                     "because the address is retired or could not be read at the last check.")
        return text

    def block_start_here(self) -> str:
        lines = ["| I want to... | Go to |", "|---|---|"]
        for row in self.tax["start_here"]:
            did, _, sid = row["to"].partition("/")
            dom = self.domains[did]
            if sid:
                title = self.section_title(did, sid)
                target = f"[{dom['title']}: {title}](domains/{did}.md#{catalog.slug(title)})"
            else:
                target = f"[{dom['title']}](domains/{did}.md)"
            lines.append(f"| {md_cell(row['want'])} | {target} |")
        return "\n".join(lines)

    def block_domains(self) -> str:
        lines = []
        for group in self.tax["groups"]:
            doms = [d for d in self.populated() if d["group"] == group["id"]]
            if not doms:
                continue
            lines += [f"**{group['title']}.** {group['note']}", "", "| Domain | What it covers | Resources |", "|---|---|---|"]
            for dom in doms:
                lines.append(f"| [{dom['title']}](domains/{dom['id']}.md) | {md_cell(dom['covers'])} | {self.domain_count(dom['id'])} |")
            lines.append("")
        planned = [d["title"] for d in self.tax["domains"] if not self.domain_count(d["id"])]
        if planned:
            lines += [f"The [domain list](domains/README.md) also defines {plural(len(planned), 'domain')} that hold no resources yet: {'; '.join(planned)}.", ""]
        return "\n".join(lines).rstrip("\n")

    def block_kinds(self) -> str:
        lines = ["| Kind | What it means |", "|---|---|"]
        lines += [f"| {k['label']} | {md_cell(k['means'])} |" for k in self.tax["kinds"]]
        lines += ["", "| Cost | What it means |", "|---|---|"]
        lines += [f"| {c['label']} | {md_cell(c['means'])} |" for c in self.tax["costs"]]
        return "\n".join(lines)

    def readme(self, current: str) -> str:
        blocks = {
            "counts": self.block_counts(),
            "start-here": self.block_start_here(),
            "domains": self.block_domains(),
            "kinds": self.block_kinds(),
        }
        for name, body in blocks.items():
            pattern = re.compile(rf"(<!-- {name}:start[^>]*-->\n).*?(<!-- {name}:end -->)", re.S)
            if not pattern.search(current):
                raise SystemExit(f"README.md has no '{name}' marker block")
            current = pattern.sub(lambda m, body=body: m.group(1) + body + "\n" + m.group(2), current)
        return current

    # ---- link-check exclusions for lychee, from the one ignore list
    def lycheeignore(self) -> str:
        lines = ["# Generated by scripts/build.py from data/link-check-ignore.yaml. Do not edit.",
                 "# One regular expression per line; each address is justified in the data file."]
        for item in self.ignore:
            lines.append("^" + re.escape(item["url"]))
        return "\n".join(lines) + "\n"

    # ---- everything
    def outputs(self) -> dict[str, str]:
        out = {
            "LINKS.md": self.links_md(),
            "bookmarks.html": self.bookmarks_html(),
            "bookmarks-full.html": self.bookmarks_full_html(),
            "INDEX.md": self.index_md(),
            "domains/README.md": self.domains_readme(),
            ".lycheeignore": self.lycheeignore(),
        }
        for dom in self.populated():
            out[f"domains/{dom['id']}.md"] = self.domain_page(dom)
        readme = ROOT / "README.md"
        out["README.md"] = self.readme(readme.read_text(encoding="utf-8"))
        return out


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def read_lock() -> dict[str, str]:
    lock = {}
    for line in (catalog.DATA / "compact.lock").read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            digest, name = line.split()
            lock[name] = digest
    return lock


def main(argv: list[str]) -> int:
    check = "--check" in argv
    cat = Catalog()
    outputs = cat.outputs()
    problems = []

    lock = read_lock()
    for name in ("LINKS.md", "bookmarks.html"):
        if lock.get(name) != sha256(outputs[name]):
            problems.append(f"{name}: the data produces sha256 {sha256(outputs[name])}, data/compact.lock expects {lock.get(name)}. "
                            "If the compact set was changed on purpose, update the lock in the same change.")

    expected_pages = {p for p in outputs if p.startswith("domains/")}
    for path in sorted((ROOT / "domains").glob("*.md")):
        rel = f"domains/{path.name}"
        if rel not in expected_pages:
            problems.append(f"{rel}: no populated domain produces this page; delete it")

    for rel, text in outputs.items():
        path = ROOT / rel
        if check:
            on_disk = path.read_bytes() if path.exists() else None
            if on_disk != text.encode("utf-8"):
                problems.append(f"{rel}: differs from what the data produces; run python scripts/build.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)

    if check:
        if problems:
            print("\n".join(problems))
            print(f"build --check: {len(problems)} problem(s)")
            return 1
        print(f"build --check: {len(outputs)} generated files match the data; compact lock matches")
        return 0
    print(f"build: wrote {len(outputs)} files ({len(cat.active)} resources shown, {len(expected_pages) - 1} domain pages)")
    lock_problems = [p for p in problems if "compact.lock" in p or "no populated domain" in p]
    if lock_problems:
        print("\n".join(lock_problems))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
